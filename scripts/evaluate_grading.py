"""Does the retrieval grader actually improve the evidence? Measure it.

    python scripts/evaluate_grading.py                 # the whole golden set
    python scripts/evaluate_grading.py --limit 4       # a cheap smoke test
    python scripts/evaluate_grading.py --k 3           # stricter cut-off

The agentic loop this version added is: search, judge what came back, and if it
was poor, rewrite the query and search again. That is a claim about quality, and
a claim about quality that has not been measured is a claim.

**The comparison.** Each question is retrieved for twice, differing in one
setting:

    ungraded    CC_GRADING_ENABLED=false  - search once, answer from whatever
    graded      CC_GRADING_ENABLED=true   - search, judge, re-query if thin

Everything else is held constant, including the query analysis AND the expanded
query plan, both computed once per question and handed to both runs. A
difference in the numbers is therefore the loop and nothing else.

Sharing the plan is a correction. The first run of this experiment let each side
expand its own query, and because translation is generated by a model the two
sides searched for different things before grading was involved at all. On 3 of
the 23 questions where grading changed nothing, the ranking moved anyway - a 13%
noise floor, wider than the improvement being claimed, which is why that run
could only say the loop fires and not that it helps.

**The metrics are deterministic. There is no LLM judging its own homework.**
The golden set carries, for each question, which document should be found and
which section of it - so:

    hit@k  the expected source appears in the top k passages
    MRR    mean reciprocal rank of the first expected passage (1.0 = always #1)

reported at document level (was the right file found) and at section level (was
the right *part* of it found), because retrieving the right file and the wrong
paragraph is a failure that a document-level number hides.

**The honest bit.** The loop can only help on questions where it fires - where
the grader said the evidence was weak and went back out. The headline table
therefore matters less than the last one, which reports the subset where a
second round actually ran. If the numbers do not move there, the feature does
not work, and this script is designed to be able to say so.

Cost: roughly one analysis, two translations and one or two grading calls per
question, plus reranking. On a laptop CPU expect a minute or so per question,
most of it in the cross-encoder. Start with `--limit 4`.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from career_copilot.core.config import get_settings
from career_copilot.core.errors import CopilotError
from career_copilot.core.logging import configure_logging
from career_copilot.core.session import use_session
from career_copilot.core.usage import session_totals
from career_copilot.rag.pipeline import GradedRetrieval, Source, retrieve_graded
from career_copilot.rag.query_analysis import QueryAnalysis, analyse_query
from career_copilot.rag.translate import QueryPlan, expand_query
from career_copilot.rag.warmup import warm_models

GOLDEN_SET = Path("tests/eval/golden_set.json")
REPORT = Path("docs/evaluation.md")
RAW = Path("data/eval/grading_ab.json")


@dataclass(frozen=True)
class Config:
    """One side of the comparison, as environment settings."""

    name: str
    grading_enabled: bool
    max_rounds: int
    blurb: str


CONFIGS = (
    Config("ungraded", False, 1, "search once, answer from whatever came back"),
    Config("graded", True, 2, "search, judge the evidence, re-query once if it is thin"),
)


@dataclass
class Score:
    """hit@k and MRR, accumulated."""

    hits: int = 0
    reciprocal_ranks: float = 0.0
    total: int = 0

    @property
    def hit_rate(self) -> float:
        return self.hits / self.total if self.total else 0.0

    @property
    def mrr(self) -> float:
        return self.reciprocal_ranks / self.total if self.total else 0.0

    def record(self, rank: int | None) -> None:
        self.total += 1
        if rank is not None:
            self.hits += 1
            self.reciprocal_ranks += 1.0 / rank


@dataclass
class Outcome:
    """What one configuration did with one question."""

    config: str
    doc_rank: int | None
    section_rank: int | None
    rounds: int
    verdict: str
    graded: bool
    queries: list[str]
    sources: list[dict[str, str]]
    latency_ms: float
    cost_usd: float
    calls: int


@dataclass
class Row:
    """One question, both configurations."""

    question: str
    expected: list[str]
    expected_sections: list[str]
    why_hard: str
    outcomes: dict[str, Outcome] = field(default_factory=dict)

    @property
    def requeried(self) -> bool:
        """Whether the graded run actually went back out for more.

        The only questions on which the feature can possibly have an effect.
        """
        graded = self.outcomes.get("graded")
        return graded is not None and graded.rounds > 1


def _rank_of(
    sources: list[Source], expected: list[str], sections: list[str] | None, k: int
) -> int | None:
    """1-based rank of the first passage that matches, or None.

    A section match requires the document to match too - the right heading in
    the wrong file is a coincidence, not a hit.
    """
    for position, source in enumerate(sources[:k], start=1):
        if source.source not in expected:
            continue
        if sections is None:
            return position
        if source.section and source.section in sections:
            return position
    return None


def _apply(config: Config) -> None:
    """Point the settings at one configuration.

    Written to the environment rather than passed as arguments because that is
    how the pipeline reads them, and a benchmark that took a different code
    path from the application would be measuring something else.
    """
    os.environ["CC_GRADING_ENABLED"] = "true" if config.grading_enabled else "false"
    os.environ["CC_MAX_RETRIEVAL_ROUNDS"] = str(config.max_rounds)
    get_settings.cache_clear()


def _run_one(
    question: str, analysis: QueryAnalysis, plan: QueryPlan, session_id: str
) -> tuple[GradedRetrieval, float, Any]:
    before = session_totals(session_id)
    started = time.perf_counter()
    with use_session(session_id):
        result = retrieve_graded(question, analysis=analysis, plan=plan, session_id=session_id)
    elapsed = (time.perf_counter() - started) * 1000
    return result, elapsed, session_totals(session_id).since(before)


def _evaluate(questions: list[dict[str, Any]], k: int) -> list[Row]:
    rows: list[Row] = []

    for number, item in enumerate(questions, start=1):
        question = item["question"]
        expected = item["expected"]
        sections = item.get("expected_sections") or []
        print(f"\n[{number}/{len(questions)}] {question[:70]}")

        # Both of these are computed once and handed to both sides.
        #
        # The analysis was already shared: it describes what was asked, which
        # the setting under test does not change.
        #
        # The PLAN was not, and that was the flaw in the first run of this
        # experiment. Query translation is generated by a model, so each side
        # got its own expanded query set, and the two configurations searched
        # for different things before grading ever entered the picture. The
        # measured effect included that sampling: on 3 of the 23 questions
        # where grading changed nothing at all, the ranking still moved - a 13%
        # noise floor, wider than the difference being claimed. Sharing the plan
        # is what makes the remaining difference attributable to the loop.
        _apply(CONFIGS[0])
        session = f"eval-analysis-{number}"
        try:
            with use_session(session):
                analysis = analyse_query(question, session_id=session)
        except CopilotError as exc:
            print(f"    query analysis failed ({exc.user_message}) - using an empty one")
            analysis = QueryAnalysis()

        try:
            with use_session(session):
                plan = expand_query(question, analysis=analysis, session_id=session)
        except CopilotError as exc:
            print(f"    query translation failed ({exc.user_message}) - using the raw question")
            plan = QueryPlan(original=question, keywords=analysis.keywords)

        row = Row(question, expected, sections, item.get("why_hard", ""))
        for config in CONFIGS:
            _apply(config)
            session = f"eval-{config.name}-{number}"
            try:
                result, elapsed, spent = _run_one(question, analysis, plan, session)
            except CopilotError as exc:
                print(f"    {config.name:<9} FAILED - {exc.user_message}")
                continue

            outcome = Outcome(
                config=config.name,
                doc_rank=_rank_of(result.sources, expected, None, k),
                section_rank=_rank_of(result.sources, expected, sections, k) if sections else None,
                rounds=len(result.rounds),
                verdict=result.grade.verdict,
                graded=result.grade.graded,
                queries=[r.query for r in result.rounds],
                sources=[
                    {"source": s.source, "section": s.section or ""} for s in result.sources[:k]
                ],
                latency_ms=elapsed,
                cost_usd=spent.cost_usd,
                calls=spent.calls,
            )
            row.outcomes[config.name] = outcome
            mark = "hit" if outcome.doc_rank else "miss"
            print(
                f"    {config.name:<9} {mark:<4} doc@{outcome.doc_rank or '-'} "
                f"sec@{outcome.section_rank or '-'} rounds={outcome.rounds} "
                f"verdict={outcome.verdict} {outcome.latency_ms / 1000:.1f}s"
            )
        rows.append(row)

    return rows


def _tally(rows: list[Row], attribute: str) -> dict[str, Score]:
    scores = {config.name: Score() for config in CONFIGS}
    for row in rows:
        for name, score in scores.items():
            outcome = row.outcomes.get(name)
            if outcome is None:
                continue
            score.record(getattr(outcome, attribute))
    return scores


def _table(scores: dict[str, Score], title: str) -> list[str]:
    lines = [f"### {title}", "", "| configuration | hit@k | MRR | n |", "|---|---|---|---|"]
    for config in CONFIGS:
        score = scores[config.name]
        lines.append(f"| {config.name} | {score.hit_rate:.0%} | {score.mrr:.3f} | {score.total} |")
    lines.append("")
    return lines


def _report(rows: list[Row], k: int) -> str:
    fired = [row for row in rows if row.requeried]
    graded = [row.outcomes["graded"] for row in rows if "graded" in row.outcomes]
    verdicts: dict[str, int] = {}
    for outcome in graded:
        verdicts[outcome.verdict] = verdicts.get(outcome.verdict, 0) + 1

    lines = [
        "# Does the retrieval grader earn its place?",
        "",
        f"`scripts/evaluate_grading.py`, {len(rows)} questions from "
        "`tests/eval/golden_set.json`, k={k}.".replace("{k}", str(k)),
        "",
        "Two runs per question, differing in one setting: whether the evidence is",
        "graded and re-queried. The query analysis is computed once and shared.",
        "",
        "| configuration | what it does |",
        "|---|---|",
    ]
    lines += [f"| `{c.name}` | {c.blurb} |" for c in CONFIGS]
    lines += [
        "",
        "Metrics are deterministic — the golden set says which document and which",
        "section each question should reach, so nothing here is a model marking its",
        "own work.",
        "",
        "## Overall",
        "",
    ]
    lines += _table(_tally(rows, "doc_rank"), "Document level — was the right file found?")
    lines += _table(_tally(rows, "section_rank"), "Section level — was the right part of it found?")

    quiet = [row for row in rows if not row.requeried and len(row.outcomes) == len(CONFIGS)]
    noisy = [
        row for row in quiet if row.outcomes["ungraded"].doc_rank != row.outcomes["graded"].doc_rank
    ]
    noise = len(noisy) / len(quiet) if quiet else 0.0

    lines += [
        "## How much of this is noise",
        "",
        "On a question where the grader approves the first round, the two",
        "configurations **must** retrieve identically: grading judges round one, it",
        "does not change it. Any difference on those questions is measurement noise,",
        "and measuring it is what makes the rest of this report readable.",
        "",
        f"- Questions where the loop did not fire: **{len(quiet)}**",
        f"- Of those, the document rank still differed: **{len(noisy)}** (**{noise:.0%}**)",
        "",
    ]
    if noisy:
        lines += [f"  - {row.question[:70]}" for row in noisy]
        lines += [
            "",
            "The cause is that query *translation* — the paraphrases fed to the",
            "search — is sampled separately for each configuration. Only the analysis",
            "is shared. So two runs of the same question search with slightly",
            "different words, and the ranking moves.",
            "",
            f"**This bounds what can be claimed.** A difference smaller than the {noise:.0%}",
            "noise floor is not evidence of anything. The overall tables below are",
            "reported for completeness, but the honest comparison is the re-queried",
            "subset, and even there the sample is small.",
            "",
        ]
    else:
        lines += [
            "Nothing differed, so the two configurations are cleanly comparable on",
            "the questions where the loop did not fire.",
            "",
        ]

    lines += [
        "## How often the loop fired",
        "",
        f"- Questions where the grader sent retrieval back out: **{len(fired)} of {len(rows)}**",
        "- Verdicts on the graded run: "
        + (", ".join(f"`{v}` x{n}" for v, n in sorted(verdicts.items())) or "none recorded"),
        "",
        "A verdict of `sufficient` on the first round means the loop cost one extra",
        "model call and changed nothing — which is the intended common case. The",
        "feature is only *capable* of helping on the questions below.",
        "",
    ]

    if fired:
        # The tables below can move on a single question and still look like a
        # trend, so say outright how many questions are behind them. A gain
        # carried by one question out of twenty-eight is an anecdote, and a
        # report that lets a reader mistake it for evidence is doing the same
        # job as a report that hides it.
        moved = [
            row
            for row in fired
            if (row.outcomes["ungraded"].doc_rank, row.outcomes["ungraded"].section_rank)
            != (row.outcomes["graded"].doc_rank, row.outcomes["graded"].section_rank)
        ]
        carried = (
            "that single question"
            if len(moved) == 1
            else f"those {len(moved)} questions"
            if moved
            else "nothing"
        )
        lines += [
            "## Where it actually fired",
            "",
            f"The loop re-queried **{len(fired)}** questions. Of those, **{len(moved)}** "
            "retrieved anything",
            "different from the single-search run \u2014 the rest searched again and landed on",
            "the ranks they already had. Every number in the two tables below is carried by",
            f"{carried}.",
            "",
        ]
        if moved:
            for row in moved:
                before, after = row.outcomes["ungraded"], row.outcomes["graded"]
                lines.append(
                    f"- {row.question[:66]} — doc {before.doc_rank} to {after.doc_rank}, "
                    f"section {before.section_rank} to {after.section_rank}"
                )
            lines.append("")
        lines += _table(
            _tally(fired, "doc_rank"), f"Document level, re-queried questions only (n={len(fired)})"
        )
        lines += _table(
            _tally(fired, "section_rank"),
            f"Section level, re-queried questions only (n={len(fired)})",
        )
        lines += ["### What it searched for instead", ""]
        for row in fired:
            outcome = row.outcomes["graded"]
            lines += [f"**{row.question}**", ""]
            for index, query in enumerate(outcome.queries, start=1):
                lines.append(f"{index}. `{query}`")
            before = row.outcomes.get("ungraded")
            lines += [
                "",
                f"- ungraded: doc rank {before.doc_rank if before else '—'}",
                f"- graded: doc rank {outcome.doc_rank}, final verdict `{outcome.verdict}`",
                "",
            ]
    else:
        lines += [
            "## Where it actually fired",
            "",
            "**Nowhere.** The grader judged the first round sufficient on every",
            "question in this set, so the re-query path never ran and the two",
            "configurations retrieved identically. The numbers above being equal is",
            "not evidence that the loop works — it is evidence that it did not run.",
            "",
            "That is a finding, not a failed run. It says the golden set is too easy",
            "for this knowledge base: 166 chunks over fourteen documents, where the",
            "first search usually does find the right file. To exercise the loop you",
            "need questions whose obvious phrasing retrieves the wrong thing.",
            "",
        ]

    cost = sum(o.cost_usd for row in rows for o in row.outcomes.values())
    latency = {
        c.name: sum(row.outcomes[c.name].latency_ms for row in rows if c.name in row.outcomes)
        / max(sum(1 for row in rows if c.name in row.outcomes), 1)
        for c in CONFIGS
    }
    calls = {
        c.name: sum(row.outcomes[c.name].calls for row in rows if c.name in row.outcomes)
        for c in CONFIGS
    }
    spend = {
        c.name: sum(row.outcomes[c.name].cost_usd for row in rows if c.name in row.outcomes)
        for c in CONFIGS
    }

    lines += [
        "## What it cost",
        "",
        "Model calls and money are the portable numbers — they are the same on any",
        "machine. Wall-clock is not, and on the machine this ran on it is badly",
        "misleading, for a reason that has nothing to do with grading: a call that",
        "follows the cross-encoder stalls for about 45 seconds here. The graded",
        "configuration makes more calls, so it collects more stalls.",
        "",
        "| configuration | model calls | cost | mean latency (this machine) |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {c.name} | {calls[c.name]} | ${spend[c.name]:.4f} | {latency[c.name] / 1000:.1f} s |"
        for c in CONFIGS
    ]
    lines += [
        "",
        f"Total for this run: **${cost:.4f}** across {len(rows)} questions x "
        f"{len(CONFIGS)} configurations.",
        "",
        "The real cost of the feature is the call count: one grading call per round,",
        "plus a full extra retrieval on the questions that are re-queried. In money",
        "that is fractions of a cent. Do not read the latency column as the cost of",
        "grading — read it as the cost of a stall this machine has.",
        "",
        "These are warm numbers. The embedder and cross-encoder are loaded before",
        "the first measurement, because they take about ninety seconds in a fresh",
        "process and whichever configuration ran first would otherwise be charged",
        "for all of it. The application pays that cost once at startup, not per",
        "question, so charging it to a question here would be measuring the",
        "benchmark rather than the feature.",
        "",
        "## Reproducing this",
        "",
        "```",
        "python scripts/evaluate_grading.py",
        "```",
        "",
        "Raw per-question results, including every passage retrieved, are written to",
        f"`{RAW}` so any number here can be checked rather than believed.",
        "",
    ]
    return "\n".join(lines)


def _load_raw() -> list[Row]:
    """Rebuild the rows from a previous run's raw results.

    A run takes hours on a laptop. Wording a conclusion better must not cost
    another one, so the report can always be regenerated from what was
    recorded - and the recorded numbers are then provably the same ones.
    """
    rows: list[Row] = []
    for item in json.loads(RAW.read_text(encoding="utf-8")):
        row = Row(
            item["question"],
            item["expected"],
            item.get("expected_sections") or [],
            item.get("why_hard", ""),
        )
        for name, outcome in item["outcomes"].items():
            row.outcomes[name] = Outcome(**outcome)
        rows.append(row)
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description="A/B the retrieval grading loop.")
    parser.add_argument("--k", type=int, default=5, help="cut-off for hit@k (default 5)")
    parser.add_argument("--limit", type=int, default=0, help="only the first N questions")
    parser.add_argument(
        "--report-only",
        action="store_true",
        help=f"rewrite the report from {RAW} without re-running anything",
    )
    args = parser.parse_args()

    configure_logging()

    if args.report_only:
        if not RAW.exists():
            print(f"no previous results at {RAW} - run without --report-only first")
            return 1
        rows = _load_raw()
        REPORT.write_text(_report(rows, args.k), encoding="utf-8")
        print(f"rebuilt {REPORT} from {len(rows)} saved results - nothing was re-run")
        return 0

    questions = json.loads(GOLDEN_SET.read_text(encoding="utf-8"))["questions"]
    if args.limit:
        questions = questions[: args.limit]

    print(f"\n{len(questions)} questions x {len(CONFIGS)} configurations, k={args.k}")
    print("This makes real model calls and runs the cross-encoder. It is not fast.\n")

    # Before the timer starts on anything, not inside the first measurement.
    # The embedder and the cross-encoder take about a minute and a half to load
    # in a fresh process, and whichever configuration ran first would otherwise
    # carry all of it - a ninety-second handicap awarded by running order rather
    # than by anything the configuration did.
    print("loading the retrieval models first, so nothing below is timed cold...")
    warm_models()
    print()

    try:
        rows = _evaluate(questions, args.k)
    except KeyboardInterrupt:
        print("\ninterrupted - nothing written")
        return 130

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    RAW.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(_report(rows, args.k), encoding="utf-8")
    RAW.write_text(
        json.dumps(
            [
                {
                    "question": row.question,
                    "expected": row.expected,
                    "expected_sections": row.expected_sections,
                    "why_hard": row.why_hard,
                    "outcomes": {name: vars(o) for name, o in row.outcomes.items()},
                }
                for row in rows
            ],
            indent=2,
        ),
        encoding="utf-8",
    )

    print(f"\nwrote {REPORT}")
    print(f"wrote {RAW}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
