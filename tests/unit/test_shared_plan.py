"""A supplied query plan is used, and only where it should be.

This pins the fix for the flaw that made the first grading experiment
inconclusive. Query translation is generated by a model, so asking for it twice
returns two different query sets; the A/B harness was letting each side expand
its own, which meant the two configurations searched for different things before
grading was involved at all. Three of the twenty-three questions where grading
changed nothing still moved in the rankings - a 13% noise floor, wider than the
improvement being claimed.

Two properties have to hold for the correction to mean anything, and each has a
test below:

    round one uses the plan it was given, so both sides search identically
    round two does NOT, because the retry exists to search for something else

The second is the one worth guarding. Reusing round one's queries on the retry
would turn the loop into a repeat: the grader asks for a different search, the
pipeline performs the same one, and the second round returns the passages that
were already judged thin. The feature would still appear to fire, and would do
nothing - which is precisely the class of silent failure this project has been
bitten by before.

No model is called here. What is under test is which queries reach the search.
"""

from __future__ import annotations

import pytest

from career_copilot.rag import pipeline
from career_copilot.rag.grader import EvidenceGrade
from career_copilot.rag.query_analysis import QueryAnalysis
from career_copilot.rag.translate import QueryPlan


@pytest.fixture()
def spy(monkeypatch):
    """Record the plan each retrieval round searched with."""
    seen: list[QueryPlan] = []

    def _search(plan, **_kwargs):
        seen.append(plan)
        return []

    monkeypatch.setattr(pipeline, "hybrid_search", _search)
    monkeypatch.setattr(pipeline, "rerank", lambda *_a, **_k: [])
    monkeypatch.setattr(
        pipeline,
        "expand_query",
        lambda question, **_k: QueryPlan(original=f"expanded::{question}"),
    )
    return seen


def test_a_supplied_plan_is_searched_with_rather_than_a_fresh_one(spy, monkeypatch):
    """The whole point: both sides of the A/B search for the same thing."""
    monkeypatch.setattr(
        pipeline,
        "grade_evidence",
        lambda *_a, **_k: EvidenceGrade(verdict="sufficient", reason="", graded=True),
    )
    given = QueryPlan(original="the shared query")

    pipeline.retrieve_graded("what is a TARA?", analysis=QueryAnalysis(), plan=given)

    assert [plan.original for plan in spy] == ["the shared query"]


def test_without_a_plan_the_question_is_expanded_as_usual(spy, monkeypatch):
    """The application path is untouched: nothing in it passes a plan."""
    monkeypatch.setattr(
        pipeline,
        "grade_evidence",
        lambda *_a, **_k: EvidenceGrade(verdict="sufficient", reason="", graded=True),
    )

    pipeline.retrieve_graded("what is a TARA?", analysis=QueryAnalysis())

    assert [plan.original for plan in spy] == ["expanded::what is a TARA?"]


def test_the_retry_expands_the_graders_query_instead_of_reusing_the_plan(spy, monkeypatch):
    """A retry that searched the same way would be a loop that does nothing.

    The grader asks for a different search precisely because the first one came
    back thin. If round two reused the supplied plan it would fetch the same
    passages, the verdict would not improve, and the feature would look alive
    while being inert.
    """
    verdicts = iter(
        [
            EvidenceGrade(
                verdict="weak", reason="thin", better_query="ISO 21434 risk method", graded=True
            ),
            EvidenceGrade(verdict="sufficient", reason="", graded=True),
        ]
    )
    monkeypatch.setattr(pipeline, "grade_evidence", lambda *_a, **_k: next(verdicts))
    monkeypatch.setattr(pipeline.get_settings(), "max_retrieval_rounds", 2, raising=False)

    pipeline.retrieve_graded(
        "what is a TARA?", analysis=QueryAnalysis(), plan=QueryPlan(original="the shared query")
    )

    assert len(spy) == 2
    assert spy[0].original == "the shared query"
    assert spy[1].original == "expanded::ISO 21434 risk method"
